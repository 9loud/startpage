/**
 * @param {keyof typeof PATHS} name
 * @param {{size?: number, className?: string}} [options]
 */
export function icon(name, {size = 24, className = 'icon'} = {}) {
  const path = PATHS[name];
  if (!path) {
    console.warn(`[icons] Unknown icon: ${name}`);
    return '';
  }
  return `<svg class="${className}" viewBox="0 0 24 24" width="${size}" height="${size}" aria-hidden="true" focusable="false"><path d="${path}"/></svg>`;
}

/** Returns a fully populated <md-icon> markup string. */
export function mdIcon(name, size = 24) {
  return `<md-icon>${icon(name, {size})}</md-icon>`;
}

/** Fills every [data-icon] placeholder in the given subtree. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    if (!el.firstElementChild) {
      el.innerHTML = icon(/** @type {any} */ (el.dataset.icon));
    }
  }
}
