import {build} from 'esbuild';
import {writeFile, mkdir, readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {
  Hct,
  MaterialDynamicColors,
  SchemeTonalSpot,
  TonalPalette,
  argbFromHex,
} from '@material/material-color-utilities';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');

const SEEDS = {
  primary: '#fe8019',
  secondary: '#83a598',
  tertiary: '#d3869b',
  neutral: '#8a7f74',
};

const COLORS = {
  primary: 'primary',
  onPrimary: 'on-primary',
  primaryContainer: 'primary-container',
  onPrimaryContainer: 'on-primary-container',
  secondary: 'secondary',
  onSecondary: 'on-secondary',
  secondaryContainer: 'secondary-container',
  onSecondaryContainer: 'on-secondary-container',
  tertiary: 'tertiary',
  onTertiary: 'on-tertiary',
  tertiaryContainer: 'tertiary-container',
  onTertiaryContainer: 'on-tertiary-container',
  error: 'error',
  onError: 'on-error',
  errorContainer: 'error-container',
  onErrorContainer: 'on-error-container',
  background: 'background',
  onBackground: 'on-background',
  surface: 'surface',
  onSurface: 'on-surface',
  surfaceVariant: 'surface-variant',
  onSurfaceVariant: 'on-surface-variant',
  surfaceDim: 'surface-dim',
  surfaceBright: 'surface-bright',
  surfaceContainerLowest: 'surface-container-lowest',
  surfaceContainerLow: 'surface-container-low',
  surfaceContainer: 'surface-container',
  surfaceContainerHigh: 'surface-container-high',
  surfaceContainerHighest: 'surface-container-highest',
  inverseSurface: 'inverse-surface',
  inverseOnSurface: 'inverse-on-surface',
  inversePrimary: 'inverse-primary',
  outline: 'outline',
  outlineVariant: 'outline-variant',
  shadow: 'shadow',
  scrim: 'scrim',
};

/** @param {boolean} dark */
function buildScheme(dark) {
  const scheme = new SchemeTonalSpot(
    Hct.fromInt(argbFromHex(SEEDS.primary)),
    dark,
    0,
  );
  scheme.secondaryPalette = TonalPalette.fromHct(
    Hct.fromInt(argbFromHex(SEEDS.secondary)),
  );
  scheme.tertiaryPalette = TonalPalette.fromHct(
    Hct.fromInt(argbFromHex(SEEDS.tertiary)),
  );
  scheme.neutralPalette = TonalPalette.fromHct(
    Hct.fromInt(argbFromHex(SEEDS.neutral)),
  );
  scheme.neutralVariantPalette = TonalPalette.fromHct(
    Hct.fromInt(argbFromHex(SEEDS.neutral)),
  );
  return scheme;
}

function hex(argb) {
  return `#${(argb & 0xffffff).toString(16).padStart(6, '0')}`;
}

function schemeTokens(dark) {
  const scheme = buildScheme(dark);
  const lines = [];
  for (const [dynamicName, tokenName] of Object.entries(COLORS)) {
    const dynamicColor = MaterialDynamicColors[dynamicName];
    if (!dynamicColor) {
      throw new Error(`Unknown Material dynamic color: ${dynamicName}`);
    }
    lines.push(
      `  --md-sys-color-${tokenName}: ${hex(dynamicColor.getArgb(scheme))};`,
    );
  }
  return lines.join('\n');
}

const tokens = `/**
 * Material 3 color tokens.
 * Generated by tools/build.mjs from the gruvbox-inspired seed palette.
 * Do not edit by hand — change SEEDS in tools/build.mjs and rebuild.
 */

:root,
[data-theme='dark'] {
  color-scheme: dark;
${schemeTokens(true)}
}

[data-theme='light'] {
  color-scheme: light;
${schemeTokens(false)}
}
`;

await mkdir(path.join(root, 'css'), {recursive: true});
await writeFile(path.join(root, 'css', 'tokens.css'), tokens, 'utf8');
console.log('✓ css/tokens.css');

const result = await build({
  entryPoints: [path.join(here, 'vendor-entry.js')],
  bundle: true,
  format: 'iife',
  target: ['es2020'],
  minify: true,
  legalComments: 'eof',
  outfile: path.join(root, 'vendor', 'material.js'),
  logLevel: 'warning',
});
if (result.warnings.length) {
  console.warn(result.warnings);
}
const bundle = await readFile(path.join(root, 'vendor', 'material.js'));
console.log(`✓ vendor/material.js (${(bundle.length / 1024).toFixed(1)} KiB)`);
